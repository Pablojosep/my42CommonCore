#include "ft_printf.h"

int	ft_putstr(char *s)
{
	int	i;

	i = 0;
	if (!s)
		i = ft_putstr("(null)");
	else
	{
		while (s[i] != '\0')
			write(1, &s[i++], 1);
	}
	return (i);
}
